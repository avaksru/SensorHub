#ifndef TIME_SYNC_H
#define TIME_SYNC_H

#include "esp_err.h"
#include <string>

/* ------------------------------------------------------------------ */
/* SNTP: автоматическая синхронизация времени                          */
/* ------------------------------------------------------------------ */

/* Регистрирует обработчик IP_EVENT_STA_GOT_IP: при получении IP по STA
   SNTP стартует (или перезапускается) с сервером из настройки
   «NTP сервер» вкладки «Подключение» (config_store_load_ntp). */
esp_err_t time_sync_init(void);

/* Запуск/перезапуск SNTP с сервером host. Пустая строка — сервер из
   сохранённых настроек. Повторный вызов с действующим сервером — no-op,
   вызов с другим — перезапуск с немедленной попыткой синхронизации. */
esp_err_t time_sync_apply(const std::string &host = std::string());

/* Действующий сервер SNTP; пустая строка — SNTP не запущен. */
std::string time_sync_current_host(void);

#endif
